"""Writes the Xbox 360 build's stamp header (tools/xbox360_build.py): the
version, commit and build time the XEX logs on its first line, so a test
can tell which build ran (a failed upload to the console leaves the old one).

usage: xbox360_stamp.py OUTPUT
"""

import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from tools.version import ROOT, version  # noqa: E402


def commit() -> str:
    def git(*arguments: str) -> str:
        result = subprocess.run(["git", "-C", str(ROOT), *arguments], capture_output=True, text=True)
        return result.stdout.strip() if result.returncode == 0 else ""

    head = git("rev-parse", "--short=9", "HEAD") or "unknown"
    return head + ("-dirty" if git("status", "--porcelain", "--untracked-files=no") else "")


def main() -> None:
    output = Path(sys.argv[1])
    built = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    text = (
        "/* generated by tools/xbox360_stamp.py */\n"
        f'#define XBOX360_BUILD_VERSION "{version()}"\n'
        f'#define XBOX360_BUILD_COMMIT "{commit()}"\n'
        f'#define XBOX360_BUILD_TIME "{built}"\n'
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
